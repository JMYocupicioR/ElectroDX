import fs from 'node:fs';
import path from 'node:path';

const seedPath = 'supabase/seeds/topic_quizzes_pending_validation.json';
const temarioPath = 'TEMARIO.md';
const outSqlPath = 'supabase/seeds/import_pending_quizzes.sql';

function parseTopicModules(temario) {
  const map = new Map();
  const collisions = [];
  let moduleId = null;
  let moduleNumber = 0;
  const moduleRe = /Módulo\s+(\d+)\s*:[^`]*`\(([^)]+)\)`/;
  const topicRe = /\*\*(.+?)\*\*\s+`\(([^)]+)\)`/;

  for (const line of temario.split('\n')) {
    const mod = line.match(moduleRe);
    if (mod) {
      moduleNumber = Number(mod[1]);
      moduleId = mod[2];
      continue;
    }
    if (!moduleId || line.includes('Agrupador')) continue;
    const topic = line.match(topicRe);
    if (!topic) continue;
    const topicId = topic[2];
    if (map.has(topicId)) {
      collisions.push({ topicId, kept: map.get(topicId).moduleId, skipped: moduleId });
      continue;
    }
    map.set(topicId, {
      moduleId,
      moduleNumber,
      topicTitle: topic[1],
    });
  }
  return { map, collisions };
}

function main() {
  if (!fs.existsSync(seedPath)) {
    console.error('Missing quiz seed:', seedPath);
    process.exit(1);
  }
  if (!fs.existsSync(temarioPath)) {
    console.error('Missing TEMARIO.md');
    process.exit(1);
  }

  const seed = JSON.parse(fs.readFileSync(seedPath, 'utf8'));
  const { map, collisions } = parseTopicModules(fs.readFileSync(temarioPath, 'utf8'));
  const quizzes = [];
  const unresolved = [];

  for (const quiz of seed.quizzes ?? []) {
    const resolved = map.get(quiz.topic_id);
    if (!resolved) {
      unresolved.push(quiz.topic_id);
      continue;
    }
    quizzes.push({
      ...quiz,
      module_id: resolved.moduleId,
    });
  }

  const payload = {
    meta: {
      ...(seed.meta ?? {}),
      enrichedAt: new Date().toISOString(),
      resolvedCount: quizzes.length,
      unresolvedCount: unresolved.length,
      collisionCount: collisions.length,
    },
    quizzes,
  };

  const json = JSON.stringify(payload);
  const sql = `-- Generated by scripts/import-pending-quizzes.mjs
-- Does not overwrite existing published_quizzes.topic_id
SELECT public.admin_import_pending_quizzes($pending_quiz_seed$
${json}
$pending_quiz_seed$::jsonb);
`;

  fs.mkdirSync(path.dirname(outSqlPath), { recursive: true });
  fs.writeFileSync(outSqlPath, sql, 'utf8');

  const byModule = new Map();
  for (const quiz of quizzes) {
    byModule.set(quiz.module_id, (byModule.get(quiz.module_id) ?? 0) + 1);
  }

  console.log(`Wrote ${outSqlPath}`);
  console.log(`Resolved ${quizzes.length} quizzes; skipped unresolved ${unresolved.length}`);
  if (collisions.length) {
    console.log('Duplicate topic_id (first module kept):');
    for (const row of collisions) {
      console.log(`  ${row.topicId}: ${row.kept} (skipped ${row.skipped})`);
    }
  }
  if (unresolved.length) {
    console.log('Unresolved topic_id:', unresolved.join(', '));
  }
  console.log('Per module:', Object.fromEntries(byModule));
}

main();
